// Boot smoke test: loads every module the bot loads at startup and validates the slash command
// structures, without logging in to Discord, querying the database or connecting to Redis.
// Run with `npm run smoke` after `npm run compile`. Exits non-zero on any failure.

// ISOLATE FROM REAL SERVICES ---------------------------------------------------------------------
// set before anything requires prisma so the engine check can never reach a real database
process.env.DATABASE_URL = `mysql://smoke:smoke@127.0.0.1:1/smoke`;
delete process.env.TOKEN;
// ################################################################################################


// MODULE REQUIREMENTS ----------------------------------------------------------------------------
const fs = require(`fs`);
const path = require(`path`);
const { ApplicationCommandOptionType: OptionType, ApplicationCommandType } = require(`discord.js`);
// ################################################################################################


const ROOT = path.resolve(__dirname, `..`);
const failures = [];
const fail = (message) => failures.push(message);

// placeholder cache files for clean checkouts (CI); the real ones are generated by cache/cache.js
const CACHE_STUBS = {
    'franchises.json': [{ name: `Smoke Franchise`, slug: `SMK` }],
    'teams.json': [{ slug: `SMK`, name: `Smoke Team`, tier: `RECRUIT` }],
    'mmrCache.json': [],
    'mmrTierLinesCache.json': {},
    'combineCountCache.json': [],
    'muteCache.json': [],
};

(async () => {
    const createdStubs = writeMissingCacheStubs();

    try {
        global.logger = new (require(`../src/core/logger.js`))();
        const BotClient = require(`../src/core/botClient.js`);
        const client = new BotClient();

        // a throwing loader leaves its collection half-filled, so handler checks would only add noise
        if (loadWithBotLoaders(client)) {
            validateHandlers(client);
            validateCommandStructures(client);
        }
        requireAllModules([`src`, `utils`]);
        await checkNativeModules();
        await checkDevDmGuard(client);
        await client.destroy();
    } catch (error) {
        fail(`Unexpected error: ${error.stack ?? error}`);
    } finally {
        createdStubs.forEach((file) => fs.unlinkSync(file));
    }

    if (failures.length) {
        console.error(`\nSmoke test FAILED (${failures.length}):`);
        failures.forEach((message) => console.error(`  - ${message}`));
        process.exit(1);
    }

    console.log(`\nSmoke test passed`);
    process.exit(0);
})();


// FUNCTIONS --------------------------------------------------------------------------------------

function writeMissingCacheStubs() {
    const created = [];
    for (const [file, contents] of Object.entries(CACHE_STUBS)) {
        const cachePath = path.join(ROOT, `cache`, file);
        if (fs.existsSync(cachePath)) continue;
        fs.writeFileSync(cachePath, JSON.stringify(contents));
        created.push(cachePath);
    }
    return created;
}

/** Run the same loaders bot.js runs at startup; returns false if any threw */
function loadWithBotLoaders(client) {
    const loaders = [
        [`loadSlashCommands`, `src/interactions/commands`],
        [`loadButtons`, `src/interactions/buttons`],
        [`loadSelectMenus`, `src/interactions/selectMenus`],
        [`loadAutocomplete`, `src/interactions/autocomplete`],
        [`loadEvents`, `src/events`],
    ];

    let ok = true;
    for (const [loader, directory] of loaders) {
        try {
            client[loader](directory);
        } catch (error) {
            fail(`${loader}(${directory}) threw: ${firstLine(error)}`);
            ok = false;
        }
    }
    return ok;
}

/** Every handler needs its key + execute(), and no two files may register the same key */
function validateHandlers(client) {
    const handlerSets = [
        [`slash command`, client.slashCommands, `src/interactions/commands`, `name`],
        [`button`, client.buttons, `src/interactions/buttons`, `id`],
        [`select menu`, client.selectMenus, `src/interactions/selectMenus`, `id`],
    ];

    for (const [kind, collection, directory, key] of handlerSets) {
        const fileCount = jsFiles(directory).length;
        if (collection.size !== fileCount) fail(`${fileCount} ${kind} files in ${directory}/ but ${collection.size} registered: duplicate or missing \`${key}\``);

        collection.forEach((handler, id) => {
            if (id === undefined) fail(`A ${kind} in ${directory}/ is missing \`${key}\``);
            if (typeof handler.execute !== `function`) fail(`${kind} \`${id}\` has no execute()`);
        });
    }

    client.autocompletes.forEach((handler, name) => {
        if (typeof handler.execute !== `function`) fail(`autocomplete \`${name}\` has no execute()`);
    });

    for (const file of jsFiles(`src/events`)) {
        const event = require(path.join(ROOT, `src/events`, file));
        if (!event.name || typeof event.execute !== `function`) fail(`event ${file} is missing name or execute()`);
    }
}

/** Catch definitions Discord would reject; one bad command fails the whole bulk registration */
function validateCommandStructures(client) {
    const directory = `utils/commandsStructure`;
    const names = new Set();

    for (const file of jsFiles(directory)) {
        let structure;
        try {
            structure = require(path.join(ROOT, directory, file));
        } catch (error) {
            fail(`${directory}/${file} threw on load: ${firstLine(error)}`);
            continue;
        }

        const label = `${directory}/${file}`;
        if (names.has(structure.name)) fail(`${label}: duplicate command name \`${structure.name}\``);
        names.add(structure.name);

        const isChatInput = structure.type === undefined || structure.type === ApplicationCommandType.ChatInput;
        if (isChatInput) {
            validateNameAndDescription(structure, label);
            validateOptions(structure.options ?? [], `${label} /${structure.name}`, 0);
        }

        if (!client.slashCommands.has(structure.name)) fail(`${label}: no handler in src/interactions/commands for \`${structure.name}\``);
    }

    client.slashCommands.forEach((_, name) => {
        if (!names.has(name)) fail(`src/interactions/commands: handler \`${name}\` has no structure in ${directory}/`);
    });

    if (names.size > 100) fail(`${names.size} commands exceeds Discord's limit of 100`);
}

function validateNameAndDescription(item, label) {
    if (!/^[-_'\p{L}\p{N}\p{sc=Deva}\p{sc=Thai}]{1,32}$/u.test(item.name ?? ``)) fail(`${label}: invalid name \`${item.name}\``);
    if (item.name !== item.name?.toLowerCase()) fail(`${label}: name \`${item.name}\` must be lowercase`);
    if (!item.description || item.description.length > 100) fail(`${label}: \`${item.name}\` description must be 1-100 characters`);
}

function validateOptions(options, label, depth) {
    if (options.length > 25) fail(`${label}: more than 25 options`);

    const groupTypes = [OptionType.Subcommand, OptionType.SubcommandGroup];
    const subcommandCount = options.filter((o) => groupTypes.includes(o.type)).length;
    if (subcommandCount && subcommandCount !== options.length) fail(`${label}: mixes subcommands with regular options`);

    const seen = new Set();
    let sawOptional = false;

    for (const option of options) {
        const optionLabel = `${label} ${option.name}`;
        validateNameAndDescription(option, optionLabel);

        if (!Object.values(OptionType).includes(option.type)) fail(`${optionLabel}: unknown option type \`${option.type}\``);
        if (seen.has(option.name)) fail(`${label}: duplicate option \`${option.name}\``);
        seen.add(option.name);

        if (option.type === OptionType.SubcommandGroup) {
            if (depth !== 0) fail(`${optionLabel}: subcommand groups can only be top level`);
            if ((option.options ?? []).some((o) => o.type !== OptionType.Subcommand)) fail(`${optionLabel}: groups may only contain subcommands`);
        }
        if (option.type === OptionType.Subcommand && depth > 1) fail(`${optionLabel}: subcommand nested too deep`);

        if (!groupTypes.includes(option.type)) {
            if (option.required) {
                if (sawOptional) fail(`${optionLabel}: required option after an optional one`);
            } else sawOptional = true;
        }

        const choices = option.choices ?? [];
        if (choices.length > 25) fail(`${optionLabel}: more than 25 choices`);
        if (choices.length && option.autocomplete) fail(`${optionLabel}: cannot have both choices and autocomplete`);
        for (const choice of choices) {
            if (!choice.name || choice.name.length > 100) fail(`${optionLabel}: choice name \`${choice.name}\` must be 1-100 characters`);
            if (typeof choice.value === `string` && choice.value.length > 100) fail(`${optionLabel}: choice value \`${choice.value}\` exceeds 100 characters`);
        }

        if (option.options) validateOptions(option.options, optionLabel, depth + 1);
    }
}

/** Require everything else so broken imports in modules the loaders don't reach still fail */
function requireAllModules(directories) {
    for (const directory of directories) {
        for (const file of walk(path.join(ROOT, directory))) {
            try {
                require(file);
            } catch (error) {
                fail(`${path.relative(ROOT, file)} threw on load: ${firstLine(error)}`);
            }
        }
    }
}

/** Native binaries are what break across base images and package managers */
async function checkNativeModules() {
    try {
        const { createCanvas } = require(`@napi-rs/canvas`);
        createCanvas(1, 1).toBuffer(`image/png`);
    } catch (error) {
        fail(`@napi-rs/canvas failed to render: ${error.message}`);
    }

    // P1001 ("can't reach database") proves the query engine loaded and tried the dead port
    const { prisma } = require(`../prisma/prismadb`);
    try {
        await prisma.$connect();
        fail(`Prisma connected to the placeholder database; DATABASE_URL isolation is broken`);
    } catch (error) {
        if (error.errorCode !== `P1001`) fail(`Prisma engine failed to start: ${error.message}`);
    }
}

/** The dev DM guard patches discord.js internals, so prove every DM path still hits it */
async function checkDevDmGuard(client) {
    const { User, GuildMember, DMChannel, ChannelType, UserManager, RESTJSONErrorCodes } = require(`discord.js`);
    const { installDevDmGuard } = require(`../src/core/dmGuard.js`);
    const originalCreateDM = UserManager.prototype.createDM;

    process.env.PROD = `1`;
    if (installDevDmGuard() || UserManager.prototype.createDM !== originalCreateDM) fail(`DM guard installed with PROD=1`);

    process.env.PROD = `0`;
    process.env.DEV_DMS_ENABLED = `true`;
    if (installDevDmGuard()) fail(`DM guard installed despite DEV_DMS_ENABLED=true`);

    delete process.env.DEV_DMS_ENABLED;
    if (!installDevDmGuard()) return fail(`DM guard did not install in development`);

    // the client never logs in, so a DM that slips past the guard fails with some other error
    const userData = { id: `1`, username: `smoke`, discriminator: `0` };
    const user = new User(client, userData);
    const member = new GuildMember(client, { user: userData }, { id: `2`, client });
    const dmChannel = new DMChannel(client, { id: `3`, type: ChannelType.DM, recipients: [userData] });

    const dmPaths = {
        'user.send()': () => user.send(`smoke`),
        'member.send()': () => member.send(`smoke`),
        'client.users.send()': () => client.users.send(userData.id, `smoke`),
        'DMChannel#send()': () => dmChannel.send(`smoke`),
    };

    for (const [label, send] of Object.entries(dmPaths)) {
        try {
            await send();
            fail(`DM guard let ${label} through`);
        } catch (error) {
            if (error.code !== RESTJSONErrorCodes.CannotSendMessagesToThisUser) fail(`DM guard missed ${label}: ${firstLine(error)}`);
        }
    }
}

function firstLine(error) {
    return String(error?.message ?? error).split(`\n`)[0];
}

function jsFiles(directory) {
    return fs.readdirSync(path.join(ROOT, directory)).filter((f) => f.endsWith(`.js`));
}

function walk(directory) {
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
        const fullPath = path.join(directory, entry.name);
        if (entry.isDirectory()) return walk(fullPath);
        return entry.name.endsWith(`.js`) ? [fullPath] : [];
    });
}

